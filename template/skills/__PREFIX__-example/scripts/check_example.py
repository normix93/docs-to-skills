#!/usr/bin/env python3
"""Static checks for __PRODUCT__ <artefact> files. Standard library only.

Usage:  python3 check_example.py file.json [more.json ...]
Exit 0 = no errors, 1 = errors, 2 = unreadable input.

Pattern used in every checker of this method:
  * data that changes with the product (enums, allowed fields, forbidden calls) lives in a JSON file next to this
    script, GENERATED by tools/build_references.py from the official sources — never hard-coded here;
  * ERROR = the product would reject it or it would misbehave; WARNING = legal but risky or non-idiomatic;
  * messages say what to write instead ("did you mean ...", "use ... instead"), so a model can fix its output.
"""
from __future__ import annotations

import difflib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA_FILE = os.path.join(HERE, "example_data.json")
try:
    with open(DATA_FILE, encoding="utf-8") as fh:
        DATA = json.load(fh)
except OSError:
    DATA = {"allowedTypes": ["example"], "requiredKeys": ["name", "type"]}


class Report:
    def __init__(self):
        self.errors: list[str] = []
        self.warnings: list[str] = []

    def err(self, where: str, msg: str) -> None:
        self.errors.append(f"{where}: {msg}")

    def warn(self, where: str, msg: str) -> None:
        self.warnings.append(f"{where}: {msg}")


def check(obj, rep: Report) -> None:
    items = obj if isinstance(obj, list) else [obj]
    for i, o in enumerate(items):
        w = f"[{i}]" if isinstance(obj, list) else "root"
        if not isinstance(o, dict):
            rep.err(w, "expected a JSON object")
            continue
        for k in DATA["requiredKeys"]:
            if k not in o:
                rep.err(w, f"'{k}' is required")
        t = o.get("type")
        if t is not None and t not in DATA["allowedTypes"]:
            hint = difflib.get_close_matches(str(t), DATA["allowedTypes"], n=1)
            rep.err(w, f"type '{t}' is not valid" + (f"; did you mean '{hint[0]}'?" if hint else ""))


def main(argv) -> int:
    if len(argv) < 2:
        print(__doc__)
        return 2
    failed = False
    for path in argv[1:]:
        try:
            with open(path, encoding="utf-8") as fh:
                obj = json.load(fh)
        except (OSError, ValueError) as e:
            print(f"{path}: cannot read JSON: {e}")
            return 2
        rep = Report()
        check(obj, rep)
        for e in rep.errors:
            print(f"  ERROR   {e}")
        for w in rep.warnings:
            print(f"  WARNING {w}")
        print(f"{path}: {'FAIL' if rep.errors else 'OK'} ({len(rep.errors)} error(s), {len(rep.warnings)} warning(s))")
        failed |= bool(rep.errors)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
