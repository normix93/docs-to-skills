#!/usr/bin/env python3
"""Generate the skills' references and checker data from __PRODUCT__'s official, openly licensed sources.

Usage: python3 tools/build_references.py --source <path to a checkout of the official spec/docs/source>

Rules every generator in this method follows:
  1. Read only sources whose license allows redistribution of what you extract (see docs/licensing.md of
     docs-to-skills). For text you may not redistribute, extract facts (names, types, enums) or titles + URLs only.
  2. Start every generated Markdown file with banner(): the generator, the source, its commit/version, the date
     and the license. The weekly refresh workflow ignores changes that touch only that line.
  3. Put changing data for checkers (enums, allowed fields, forbidden calls) in a JSON file next to the checker.
  4. Make the output deterministic (sorted keys, stable order) so a rebuild without upstream changes is a no-op.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "__PREFIX__-example"


def git_sha(path: Path) -> str:
    try:
        return subprocess.check_output(["git", "-C", str(path), "log", "-1", "--format=%h %cs"], text=True).strip()
    except Exception:
        return "unknown"


def banner(source: str, version: str, license_id: str) -> str:
    return (f"<!-- GENERATED by tools/build_references.py from {source} ({version}), {dt.date.today().isoformat()}. "
            f"Source license: {license_id}. Do not edit by hand. -->\n\n")


def write(path: Path, body: str, source: str, version: str, license_id: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(banner(source, version, license_id) + body.rstrip() + "\n", encoding="utf-8")


def build(source: Path) -> None:
    version = git_sha(source)
    # Example: turn a list of types found in the source into a reference table and checker data.
    # Replace this with parsing of the real source (OpenAPI spec, XSD, Java/TS annotations, docs front matter...).
    types = sorted({"example"})
    write(SKILL / "references" / "types.md",
          "# Types\n\n| Type |\n|---|\n" + "\n".join(f"| `{t}` |" for t in types),
          "<upstream repo>", version, "<SPDX id>")
    data = {"_generated": f"tools/build_references.py ({version})", "allowedTypes": types,
            "requiredKeys": ["name", "type"]}
    (SKILL / "scripts" / "example_data.json").write_text(json.dumps(data, indent=1, sort_keys=True) + "\n",
                                                         encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True, type=Path)
    build(ap.parse_args().source)
    print("references rebuilt")


if __name__ == "__main__":
    main()
