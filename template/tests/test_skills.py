"""Tests every skill repository built with this method needs. Run: python3 -m unittest discover -s tests -v

1. Checkers: files in tests/fixtures/good must pass with no errors; each file in tests/fixtures/bad must fail and
   print every line of its .expected file. Add the official examples of the product to good/ (or extract them
   at test time from the sources): if one fails, either the checker is wrong or the documentation is — record
   the latter in KNOWN_DOC_ISSUES with a link, so the test keeps detecting it.
2. Skill files: front matter, links to references/scripts that exist, GENERATED banners, JSON that parses.
"""
from __future__ import annotations

import glob
import json
import os
import re
import subprocess
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILLS = os.path.join(ROOT, "skills")
FIX = os.path.join(ROOT, "tests", "fixtures")
CHECKER = glob.glob(os.path.join(SKILLS, "*", "scripts", "check_*.py"))

# (fixture file name, substring of the error) -> why the official example is wrong
KNOWN_DOC_ISSUES: dict[tuple[str, str], str] = {}


def run(script: str, *args: str) -> tuple[int, str]:
    p = subprocess.run([sys.executable, script, *args], capture_output=True, text=True)
    return p.returncode, p.stdout + p.stderr


class Checkers(unittest.TestCase):
    def test_good_fixtures_pass(self):
        for script in CHECKER:
            for f in sorted(glob.glob(os.path.join(FIX, "good", "*.json"))):
                with self.subTest(script=os.path.basename(script), f=os.path.basename(f)):
                    code, out = run(script, f)
                    errors = [l for l in out.splitlines() if "ERROR" in l and not any(
                        os.path.basename(f) == k[0] and k[1] in l for k in KNOWN_DOC_ISSUES)]
                    self.assertEqual(errors, [], out)

    def test_bad_fixtures_fail_with_expected_errors(self):
        for script in CHECKER:
            for f in sorted(glob.glob(os.path.join(FIX, "bad", "*.json"))):
                exp = f[:-5] + ".expected"
                with open(exp, encoding="utf-8") as fh:
                    expected = [l.strip() for l in fh if l.strip()]
                with self.subTest(script=os.path.basename(script), f=os.path.basename(f)):
                    code, out = run(script, f)
                    self.assertEqual(code, 1, out)
                    for e in expected:
                        self.assertIn(e, out)


class SkillFiles(unittest.TestCase):
    def test_frontmatter(self):
        dirs = [d for d in glob.glob(os.path.join(SKILLS, "*")) if os.path.isdir(d)]
        self.assertTrue(dirs)
        for d in dirs:
            with open(os.path.join(d, "SKILL.md"), encoding="utf-8") as fh:
                text = fh.read()
            m = re.match(r"^---\nname: (.+)\ndescription: (.+?)\n---\n", text, re.S)
            with self.subTest(skill=os.path.basename(d)):
                self.assertIsNotNone(m, "front matter with name and description")
                self.assertEqual(m.group(1).strip(), os.path.basename(d))
                self.assertLessEqual(len(m.group(2)), 1024)

    def test_referenced_files_exist(self):
        for skill in glob.glob(os.path.join(SKILLS, "*", "SKILL.md")):
            with open(skill, encoding="utf-8") as fh:
                text = fh.read()
            for ref in re.findall(r"`((?:references|scripts|assets)/[\w./-]+)`", text):
                if "<" in ref:
                    continue
                with self.subTest(skill=skill, ref=ref):
                    self.assertTrue(os.path.exists(os.path.join(os.path.dirname(skill), ref)), ref)

    def test_generated_banner(self):
        for f in glob.glob(os.path.join(SKILLS, "*", "references", "**", "*.md"), recursive=True):
            with open(f, encoding="utf-8") as fh:
                head = fh.read(400)
            if "GENERATED" in head:
                self.assertRegex(head, r"GENERATED by tools/[\w./]+")

    def test_json_parses(self):
        for f in glob.glob(os.path.join(ROOT, "**", "*.json"), recursive=True):
            if "/.cache/" in f or "/runs/" in f:
                continue
            with self.subTest(f=f), open(f, encoding="utf-8") as fh:
                json.load(fh)


if __name__ == "__main__":
    unittest.main()
